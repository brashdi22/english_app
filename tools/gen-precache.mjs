// Regenerates precache-manifest.js (the list of files the service worker
// caches for offline use). Run after adding or changing files:
//   node tools/gen-precache.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const include = ['index.html', 'manifest.webmanifest', 'css', 'js', 'assets'];

function walk(path) {
  const full = join(root, path);
  if (statSync(full).isDirectory()) return readdirSync(full).sort().flatMap((f) => walk(join(path, f)));
  return [path];
}

const files = include.flatMap(walk).map((f) => relative(root, join(root, f)));
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 12);

const out = `// Generated by tools/gen-precache.mjs — do not edit by hand.
self.PRECACHE_VERSION = '${version}';
self.PRECACHE_FILES = ${JSON.stringify(['./', ...files], null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(join(root, 'precache-manifest.js'), 'utf8');
  if (current !== out) {
    console.error('precache-manifest.js is out of date. Run: node tools/gen-precache.mjs');
    process.exit(1);
  }
  console.log('precache-manifest.js is up to date');
} else {
  writeFileSync(join(root, 'precache-manifest.js'), out);
  console.log(`${files.length} files, version ${version}`);
}
